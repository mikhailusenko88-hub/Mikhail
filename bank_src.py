def rotate(bank):
    """Порядок как в config.formats: факт, миф, слово, топ-3, пословица, город."""
    order = [F, M, W, T, P, Q]
    groups = {f: [b for b in bank if b["format"] == f] for f in order}
    out = []
    while any(groups.values()):
        for f in order:
            if groups[f]:
                out.append(groups[f].pop(0))
    return out



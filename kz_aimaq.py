CHAMPS_KEY = "champions"          # особая неделя после полного круга: чемпионы всех областей
CYCLE = len(AIMAQS) + 1           # 17 областей + неделя чемпионов


def pick(turn, champ_ents=None):
    """Какая область идёт под номером turn (0, 1, 2…). Возвращает (turn, запись области).
    Неделя чемпионов бывает только если чемпионов набралось хотя бы 8 — иначе сразу следующая область."""
    turn = max(0, int(turn))
    if turn % CYCLE == len(AIMAQS):
        rows, seen = [], set()
        for c in (champ_ents or [])[-len(AIMAQS):]:
            if c.get("kk") and c["kk"] not in seen:
                seen.add(c["kk"])
                rows.append((c["kk"], c.get("ru", c["kk"]), c.get("lat", 48.0), c.get("lon", 67.0)))
        if len(rows) >= 8:
            return turn, (CHAMPS_KEY, "Облыс чемпиондары", "Чемпионы областей", "Облыс чемпиондары",
                          "Чемпионы областей", "чемпиондар", rows)
        turn += 1
    return turn, AIMAQS[turn % CYCLE]


def next_names(turn, champ_ents=None):
    """Как называется следующая неделя (каз, рус) — для объявления в финале."""
    _, a = pick(turn + 1, list(champ_ents or []) + [{"kk": f"_{i}"} for i in range(8)])
    return a[3], a[4]

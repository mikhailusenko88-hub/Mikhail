def countdown(days):
    """«Финалға дейін 3 күн · До финала 3 дня» (каз, рус) или None."""
    if days is None or days < 0:
        return None
    if days == 0:
        return ("Финал — бүгін кешке!", "Финал — сегодня вечером!")
    if days == 1:
        return ("Финал — ертең!", "Финал — завтра!")
    d = days
    ru = "день" if d % 10 == 1 and d % 100 != 11 else ("дня" if 2 <= d % 10 <= 4 and not 12 <= d % 100 <= 14 else "дней")
    return (f"Финалға дейін {d} күн", f"До финала {d} {ru}")


def stxt(league):
    return SEASON_TXT[LEAGUES[league].get("season", "week")]


def season_label(league, ch, n):
    """Подпись сезона в списке чемпионов: «3-апта · Неделя 3» или «Қараша · Ноябрь»."""
    if (ch or {}).get("label"):          # неделя области: вместо «3-апта» — название области
        return ch["label"]
    sid = (ch or {}).get("season", "")
    if LEAGUES[league].get("season") == "month" and len(sid) == 7 and sid[4] == "-":
        m = int(sid[5:]) - 1
        return f"{KZ_MONTHS[m]} · {RU_MONTHS[m]}"
    return f"{n}-апта · Неделя {n}"


def make_title(league, no, ent, final=False):
    if final:
        return f"{LEAGUES[league]['q']} 🏆 {stxt(league)['final_title']}"
    t = LEAGUES[league]["title"]
    if "{top}" in t:
        top = ""
        if t.startswith("{top}") or LEAGUES[league].get("rot"):
            # города и клубы (10.11.2026: одинаковые названия «№20» перестали цеплять): в начале названия —
            # три участника, каждый заезд другие, по кругу — зритель видит в ленте свой город
            k = (no * 3) % max(1, len(ent))
            ent = (list(ent[k:]) + list(ent[:k]))[:3]
        for e in ent:
            cand = (top + ", " if top else "") + e["kk"]
            if len(t.format(top=cand + "…", no=no)) > 90:
                break
            top = cand
        return t.format(top=top + "…", no=no)
    return t.format(no=no)


def make_desc(league, ent, final=False):
    d = _desc(league, ent)
    if final and league == "names":
        return ("🏆 Ай финалы: ұлдар ма, қыздар ма — айдың жеңімпазы анықталады!\n"
                "Финал месяца: мальчики или девочки — кто выиграет месяц?\n\n") + d
    if final:
        return stxt(league)["final_desc"] + d
    head, sep, tags = d.rpartition("\n\n")
    return head + "\n\n" + stxt(league)["note"] + sep + tags



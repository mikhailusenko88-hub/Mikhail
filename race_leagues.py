def _e(key, kk, ru, num, **kw):
    d = {"key": key, "kk": kk, "ru": ru, "num": num, "full_kk": kw.pop("full_kk", kk.upper()),
         "full_ru": kw.pop("full_ru", ru.upper())}
    d.update(kw)
    return d


def entries(league, state=None, rnd=None):
    """Участники заезда. Для имён — 10 мальчиков + 10 девочек (сначала те, кого просили в комментариях)."""
    if league == "cities":
        return [_e(kk, kk, ru, str(i + 1), lat=la, lon=lo) for i, (kk, ru, la, lo) in enumerate(CITIES)]
    if league == "regions":
        return [_e(kk, kk, ru, code, full_kk=fk, full_ru=fr, lat=la, lon=lo, code=code)
                for code, kk, ru, fk, fr, la, lo in REGIONS]
    if league == "mushel":
        return [_e(kk, kk, ru, str(i + 1), years=yrs) for i, (kk, ru, yrs) in enumerate(MUSHEL)]
    if league == "names":
        rnd = rnd or random.Random()
        st = state or {}
        used = st.get("used", {})
        req = st.get("requests", [])
        out = []
        for team, pool in (("boys", BOYS_POOL), ("girls", GIRLS_POOL)):
            asked = [n for n, t in req if t == team][:5]
            rest = [n for n in pool if n not in asked]
            rnd.shuffle(rest)
            rest.sort(key=lambda n: used.get(n, 0))     # кто реже бывал — тот первый
            out += [(n, team) for n in (asked + rest)[:10]]
        rnd.shuffle(out)
        return [_e(n, n, kz2ru(n), str(i + 1), team=t) for i, (n, t) in enumerate(out)]
    raise ValueError(f"нет такой темы: {league}")



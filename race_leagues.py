def names_in_text(text):
    """Имена из комментария (только из известного списка): [(имя, команда), ...]."""
    import re
    out = []
    words = re.findall(r"[A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]+", text or "")
    if len(words) > 12:      # длинные тексты пропускаем — там обычно не просьба
        return out
    for w in words:
        hit = NAME_INDEX.get(_norm(w))
        if hit and hit not in out:
            out.append(hit)
    return out



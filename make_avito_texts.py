def panel_size_block(x, label, width_mm, h=None, variant=0):
    area = x['w'] * x['l'] / 1e6
    box_area = round(area * x['b'], 2)
    n = math.ceil(width_mm / x['w'])
    noun = pl(n, 'панель', 'панели', 'панелей')
    hh = h or '3 м'
    if variant % 2 == 0:
        s = f'Размер: {size(x)}. Одна панель — {num(area)} м², в коробке {x["b"]} шт = {num(box_area)} м².'
    else:
        s = f'Размер панели {size(x)}, площадь одной — {num(area)} м²; в коробке {x["b"]} шт — {num(box_area)} м².'
    s += f'\nПример: {label} и высотой до {hh} — {n} {noun} ({boxes(n, x["b"])}).'
    return s


def lin_size_block(x, ex_line, variant=0):
    total = x['b'] * x['l'] / 1000
    if variant % 2 == 0:
        s = f'Размер: {size(x)}. В коробке {x["b"]} шт — {pm(total)}.'
    else:
        s = f'Размер: {size(x)}, длина одной планки {num(x["l"] / 1000)} м. В коробке {x["b"]} шт — {pm(total)}.'
    return s + '\n' + ex_line


def series_line(a, i):
    s = a.split('-')[0]
    others = [y for y in CAT if y['c'] == 'color' and y['a'].split('-')[0] == s and y['a'] != a]
    names = []
    for y in others:
        d = y['d'].split(',')[0].strip()
        if d not in names and d != BY[a]['d'].split(',')[0].strip():
            names.append(d)
    k = i % len(names)
    names = names[k:] + names[:k]
    lst = ', '.join(names[:5])
    v = i % 3
    if v == 0:
        return f'В серии {s} есть и другие декоры: {lst} и др. — спрашивайте.'
    if v == 1:
        return f'Такой же рисунок ({SERIES_LAM[s]}) есть и в других декорах: {lst} и др.'
    return f'Другие оттенки серии {s}: {lst} и др. — подберём под ваш интерьер.'


def build_new():
    out = {}
    counters = {}

    def nxt(c):
        counters[c] = counters.get(c, -1) + 1
        return counters[c]

    for x in CAT:
        a, c = x['a'], x['c']
        if c == 'panel' and a in PANELS:
            i = nxt('panel'); p = PANELS[a]
            parts = [p['intro'], panel_size_block(x, *p['ex'], h=p.get('h'), variant=i),
                     MAT_P[i % 4], MON['panel'][i % 3]]
            if p.get('tip'):
                parts.append(p['tip'])
            parts.append(SALE_WALL[i % 3])
        elif c == 'color' and a in COLORS:
            i = nxt('color'); p = COLORS[a]
            s = a.split('-')[0]
            decor = x['d'].split(',')[0].strip()
            kind = 'под бетон' if 'бетон' in decor else 'под дерево'
            head = (f'Реечная панель {kind} ARTDEC {a} (артикул поставщика QZ{a}), декор «{decor}». '
                    f'{p["intro"]} Панель уже окрашена — красить не нужно.')
            parts = [head, panel_size_block(x, *p['ex'], variant=i), p['combo'],
                     MAT_C[i % 4], MON['color'][i % 3], series_line(a, i), SALE_WALL[i % 3]]
        elif c == 'mold' and a in MOLDS:
            i = nxt('mold'); p = MOLDS[a]
            if p['ex'] == 'custom':
                exl = p['exs']
            elif p['ex'] == 'plinth':
                exl = 'Пример: в роли плинтуса на комнату 4×5 м (периметр 18 м) — 9 шт, с запасом на подрезку — 10.'
            else:
                exl = MOLD_EX[p['ex']]
            parts = [p['intro'], lin_size_block(x, exl, i), MAT_P[i % 4], MON['mold'][i % 3], SALE_WALL[i % 3]]
        elif c == 'plinth' and a in PLINTHS:
            i = nxt('plinth'); p = PLINTHS[a]
            parts = [p['intro'], lin_size_block(x, PLINTH_EX[i % 4], i), MAT_P[i % 4], MON['plinth'][i % 3]]
            if p.get('tip'):
                parts.append(p['tip'])
            parts.append(SALE_ROOM[i % 3])
        elif c == 'cornice' and a in CORNICES:
            i = nxt('cornice'); p = CORNICES[a]
            parts = [p['intro'], lin_size_block(x, CORNICE_EX[p.get('ex', i) % 4], i), MAT_P[i % 4],
                     p.get('mon') or MON['cornice'][i % 2], SALE_ROOM[i % 3]]

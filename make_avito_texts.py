# ---------- helpers ----------
def pl(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def num(x):
    s = f'{x:.2f}'.rstrip('0').rstrip('.')
    return s.replace('.', ',')


def boxes(n, b):
    k, r = divmod(n, b)
    if k == 0:
        return f'{n} шт, неполная коробка'
    kb = f'{k} {pl(k, "коробка", "коробки", "коробок")}'
    return kb if r == 0 else f'{kb} + {r} шт'


def pm(n):
    return f'{num(n)} {pl(n, "погонный метр", "погонных метра", "погонных метров")}' if n == int(n) else f'{num(n)} погонных метра'


def size(x):
    return f'{x["w"]}×{x["t"]}×{x["l"]} мм'



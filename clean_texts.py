#!/usr/bin/env python3
"""Чистка текстов объявлений «Наш декор» под правила магазина (10.11.2026).

Правила:
  • бренд поставщика (ARTDEC) не упоминаем — продвигаем «Наш декор»;
  • класс / группу горючести (Г1, Г2 …) не пишем — испытаний никто не проходил;
  • слово «рамки» не используем (правило фирменного стиля) — пишем «контур», «прямоугольник», «буазери», «обрамление».

Запуск:  python3 clean_texts.py avito_texts.json   — перезаписывает файл очищенными текстами.
build_feed.py вызывает clean() для каждого заголовка и описания, так что фид чистый,
даже если тексты сгенерируют заново старым генератором.
"""
import json
import re
import sys

# Точные замены фраз со словом «рамка» (из текущих текстов). Порядок важен: длинные — раньше.
FRAME_PHRASES = [
    ('три рамки 0,8×1,6 м на стене спальни — по 3 шт на рамку',
     'три прямоугольника 0,8×1,6 м на стене спальни — по 3 шт на каждый'),
    ('одна рамка 1×2 м — 6 м молдинга', 'прямоугольник 1×2 м по периметру — 6 м молдинга'),
    ('Рамки и линии на стене', 'Контуры и линии на стене'),
    ('рамка вокруг зеркала', 'обрамление зеркала'),
    ('рамка заметна на стене', 'контур заметен на стене'),
    ('для деликатных рамок, внутренней рамки в двойном буазери',
     'для деликатных контуров, внутреннего контура в двойном буазери'),
    ('Даёт выразительную рамку', 'Даёт выразительный контур'),
    ('крупные рамки-буазери', 'крупные прямоугольники буазери'),
    ('рамки в больших помещениях', 'буазери в больших помещениях'),
    ('рамки в коридоре', 'буазери в коридоре'),
    ('рамки в гостиной и спальне', 'буазери в гостиной и спальне'),
    ('геометрические рамки', 'геометрические контуры'),
    ('рамка выглядит богаче', 'контур выглядит богаче'),
    ('крупные рамки в залах', 'крупные прямоугольники буазери в залах'),
    ('даже узкая рамка хорошо читается', 'даже узкий контур хорошо читается'),
    ('крупные рамки, обрамление каминного портала', 'крупное буазери, обрамление каминного портала'),
    ('тонкие рамки, разделение стены', 'тонкие контуры, разделение стены'),
    ('для рамок в спальне и детской, внутренней рамки буазери',
     'для буазери в спальне и детской, внутреннего контура буазери'),
    ('углы рамок запиливаются под 45°', 'углы запиливаются под 45°'),
    ('для основных рамок буазери', 'для основных контуров буазери'),
    ('для рамок-буазери', 'для буазери'),
    ('Для рамок в спальне и гостиной', 'Для буазери в спальне и гостиной'),
    ('Для крупных рамок в гостиной', 'Для крупного буазери в гостиной'),
    ('для классических рамок на стенах', 'для классического буазери на стенах'),
    ('и рамок на обоях', 'и контуров на обоях'),
    ('для деликатных рамок на стенах и потолке, внутренних рамок буазери',
     'для деликатных контуров на стенах и потолке, внутренних контуров буазери'),
    ('для минималистичных рамок и реечных композиций', 'для минималистичных контуров и реечных композиций'),
    ('внутренних рамок буазери', 'внутренних контуров буазери'),
    ('внутренних рамок,', 'внутренних контуров,'),
    ('рамок на потолке', 'контуров на потолке'),
]

FORBIDDEN = [
    (re.compile(r'\bARTDEC\b|АРТДЕК|art-dec', re.I), 'бренд поставщика'),
    (re.compile(r'горюч|\bГ[1-4]\b|пожарн', re.I), 'класс горючести'),
    (re.compile(r'рамк|рамок', re.I), 'слово «рамки»'),
]


def clean(text):
    if not text:
        return text
    s = text
    # 1) класс горючести — целым предложением
    s = re.sub(r'[ \t]*Группа горючести Г[1-4]\.?', '', s)
    s = re.sub(r'[ \t]*[Кк]ласс горючести Г[1-4]\.?', '', s)
    # 2) бренд поставщика
    s = re.sub(r'\s*\bARTDEC\b', '', s)
    # 3) «рамки»
    for old, new in FRAME_PHRASES:
        s = s.replace(old, new)
    # косметика: двойные пробелы, пробел перед знаками, пустые хвосты строк
    s = re.sub(r'[ \t]{2,}', ' ', s)
    s = re.sub(r' +([,.;:!?)])', r'\1', s)
    s = re.sub(r'[ \t]+\n', '\n', s)
    s = re.sub(r'\n{3,}', '\n\n', s)
    return s.strip()


def problems(text):
    return [name for rx, name in FORBIDDEN if rx.search(text or '')]


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else 'avito_texts.json'
    data = json.load(open(path, encoding='utf-8'))
    changed, left = 0, []
    for d in data:
        for f in ('title', 'description'):
            new = clean(d.get(f, ''))
            if new != d.get(f, ''):
                d[f] = new
                changed += 1
            for p in problems(new):
                left.append(f"{d['a']} ({f}): {p}")
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write('\n')
    print(f'Изменено полей: {changed}')
    if left:
        print('ОСТАЛОСЬ (поправить вручную):')
        for x in left:
            print('  -', x)
        sys.exit(1)
    print('Бренда поставщика, класса горючести и слова «рамки» в текстах нет.')


if __name__ == '__main__':
    main()

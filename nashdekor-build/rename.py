#!/usr/bin/env python3
"""Переименовать товары в CAT (0f7s1eez/index.html) по формуле из SEO-задания 09.11.2026 (вечер):
  {Тип} {цвет/покрытие} под покраску [{высота} мм], {свойства}, {Ш}×{Т}×{Д} мм — {артикул}
Примеры из задания:
  «Плинтус напольный белый под покраску 80 мм, ударопрочный влагостойкий, 80×14×2000 мм — A005»
  «Стеновая реечная панель белая под покраску, ударопрочная, 180×10×3000 мм — A907»
Материал в описании — «полистирол высокой плотности (дюрополимер)». Запуск из корня репозитория, потом build.py.
Повторный запуск безопасен: формула считается заново из размеров и признаков (LED, кабель-канал, декор).
"""
import json, os

SITE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "0f7s1eez")
p = os.path.join(SITE, "index.html")
src = open(p, encoding="utf-8").read()
i = src.index("const CAT=") + len("const CAT="); depth = 0
for j in range(i, len(src)):
    if src[j] == "[": depth += 1
    elif src[j] == "]":
        depth -= 1
        if depth == 0: end = j + 1; break
CAT = json.loads(src[i:end])

MAT = "полистирол высокой плотности (дюрополимер)"
# Первый фрагмент описания («широкие ламели с тонкими швами», «дуб натуральный», размеры) — это «профиль/декор»;
# у погонажа первым идёт размер, профиль не описан. Берём его только если это не размеры.
def first_part(d):
    f = d.split(",")[0].strip()
    return "" if "×" in f or f.startswith("высота") else f

def dims(x): return "%d×%d×%d мм" % (x["w"], x["t"], x["l"])

for x in CAT:
    a, c, d = x["a"], x["c"], x["d"]
    f = first_part(d)
    led = "LED" in d or "подсветк" in d
    cable = "канал" in d
    uni = "универсальн" in d or "наличник" in d
    if c == "panel":
        x["n"] = "Стеновая реечная панель белая под покраску, ударопрочная, %s — %s" % (dims(x), a)
        x["d"] = "%s%s, %s, ударопрочная, влагостойкая, под покраску — белая, красится в любой цвет" % ((f + ", ") if f else "", dims(x), MAT)
    elif c == "color":
        decor = f or "готовый декор"
        kind = "под бетон" if "бетон" in decor else "под дерево"
        x["n"] = "Стеновая реечная панель %s «%s», готовый декор, %s — %s" % (kind, decor, dims(x), a)
        x["d"] = "декор «%s» на чёрной основе, %s, %s, ударопрочная, влагостойкая — красить не нужно" % (decor, dims(x), MAT)
    elif c == "mold":
        extra = " с кабель-каналом" if cable else (" универсальный" if uni else "")
        x["n"] = "Молдинг для стен белый под покраску%s, ударопрочный, %s — %s" % (extra, dims(x), a)
        tail = ", сзади канал под кабель" if cable else (", подходит как молдинг, плинтус или наличник" if uni else "")
        x["d"] = "%s, %s, ударопрочный, влагостойкий, под покраску — белый%s" % (dims(x), MAT, tail)
    elif c == "plinth":
        x["n"] = "Плинтус напольный %sбелый под покраску %d мм, ударопрочный влагостойкий, %s — %s" % ("с подсветкой " if led else "", x["w"], dims(x), a)
        x["d"] = "высота %d мм, %s, %s, ударопрочный, влагостойкий, под покраску — белый%s" % (x["w"], dims(x), MAT, ", паз под LED-ленту" if led else "")
    elif c == "cornice":
        x["n"] = "Потолочный плинтус %sбелый под покраску, ударопрочный, %s — %s" % ("с подсветкой " if led else "", dims(x), a)
        x["d"] = "%s, %s, ударопрочный, влагостойкий, под покраску — белый%s" % (dims(x), MAT, ", ниша под LED-ленту — парящий потолок" if led else "")
    elif c == "corner":
        x["n"] = "Уголок декоративный белый под покраску, ударопрочный, %s — %s" % (dims(x), a)
        x["d"] = "%s, для внешних углов и торцов стеновых панелей, %s, под покраску — белый" % (dims(x), MAT)

new = json.dumps(CAT, ensure_ascii=False, separators=(",", ":"))
src = src[:i] + new + src[end:]
open(p, "w", encoding="utf-8").write(src)
print("переименовано:", len(CAT))
for x in CAT[:2] + [y for y in CAT if y["a"] in ("2-7", "A35/2", "A11-80", "A503", "A116", "A005")]: print(" ", x["n"], "|", x["d"])
